GLYPHS = dict((k, v.split("|")) for k, v in _RAW.items())
W, H = 3, 5


def text_width(s, spacing=1):
    return max(0, len(s) * (W + spacing) - spacing)


def draw_text(img, x, y, text, color=(255, 255, 255, 255), spacing=1, scale=1):
    """Blit `text` onto an rgba grid in place. Unknown characters render blank."""
    ih = len(img); iw = len(img[0]) if ih else 0
    cx = x
    for ch in str(text).upper():
        g = GLYPHS.get(ch, GLYPHS[" "])
        for row in range(H):
            for col in range(W):
                if g[row][col] != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        px, py = cx + col * scale + sx, y + row * scale + sy
                        if 0 <= px < iw and 0 <= py < ih:
                            img[py][px] = color
        cx += (W + spacing) * scale
    return img
